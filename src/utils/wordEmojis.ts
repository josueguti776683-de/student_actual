/**
 * Converts a single emoji grapheme into its official Twemoji SVG CDN URL.
 */
export function getTwemojiUrl(grapheme: string): string {
  const clean = grapheme.indexOf("\u200d") < 0 ? grapheme.replace(/\ufe0f/g, "") : grapheme;
  const pts: string[] = [];
  for (const ch of Array.from(clean)) {
    const cp = ch.codePointAt(0);
    if (cp) pts.push(cp.toString(16));
  }
  return `https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/svg/${pts.join("-")}.svg`;
}

/**
 * Splits an emoji string into individual grapheme clusters (e.g. "2️⃣5️⃣" -> ["2️⃣", "5️⃣"]).
 */
export function splitEmojiGraphemes(emojiStr: string): string[] {
  if (!emojiStr) return [];
  if (typeof Intl !== "undefined" && (Intl as any).Segmenter) {
    const seg = new (Intl as any).Segmenter("en", { granularity: "grapheme" });
    return Array.from(seg.segment(emojiStr), (s: any) => s.segment).filter((s: string) => s.trim().length > 0);
  }
  return [emojiStr];
}

